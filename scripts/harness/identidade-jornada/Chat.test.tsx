// @vitest-environment jsdom
import { afterEach, describe, expect, it } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { Chat } from './Chat'

afterEach(cleanup)
describe('comunicador demonstrativo da hunt', () => {
  it('começa compacto com Log somente leitura e troca canais sem abrir o menu Social', () => {
    render(<Chat />)
    expect(screen.queryByText('Conversas', { exact: true })).toBeNull()
    expect(screen.getByRole('region', { name: 'Mensagens de Log' })).toBeTruthy()
    expect(screen.queryByRole('textbox')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Mundo' }))
    expect(screen.getByRole('region', { name: 'Mensagens de Mundo' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Expandir Conversas' }))
    expect(screen.getByRole('textbox', { name: 'Mensagem para Mundo' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Log' }))
    expect(screen.queryByRole('textbox')).toBeNull()
    expect(screen.getByText('Log da hunt · somente leitura')).toBeTruthy()
  })
  it('envia apenas mensagens demonstrativas locais, ignora espaços e preserva o canal ao minimizar', () => {
    render(<Chat />)
    fireEvent.click(screen.getByRole('button', { name: 'Comércio' }))
    fireEvent.click(screen.getByRole('button', { name: 'Expandir Conversas' }))
    const input = screen.getByRole('textbox', { name: 'Mensagem para Comércio' })
    fireEvent.change(input, { target: { value: '   ' } })
    expect((screen.getByRole('button', { name: 'Enviar mensagem demonstrativa' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(input, { target: { value: 'Olá, treinadores!' } })
    fireEvent.submit(input.closest('form')!)
    expect(screen.getByText('Olá, treinadores!')).toBeTruthy()
    expect((input as HTMLInputElement).value).toBe('')
    fireEvent.click(screen.getByRole('button', { name: 'Minimizar Conversas' }))
    expect(screen.queryByRole('region', { name: 'Comunicador de jornada' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Conversas' }))
    expect(screen.getByRole('region', { name: 'Mensagens de Comércio' })).toBeTruthy()
    expect(screen.getByText('Olá, treinadores!')).toBeTruthy()
  })
  it('não desloca o histórico antigo ao receber uma mensagem local e oferece novas mensagens', () => {
    render(<Chat />)
    fireEvent.click(screen.getByRole('button', { name: 'Mundo' }))
    fireEvent.click(screen.getByRole('button', { name: 'Expandir Conversas' }))
    const history = screen.getByRole('region', { name: 'Mensagens de Mundo' })
    Object.defineProperty(history, 'scrollHeight', { configurable: true, value: 900 })
    Object.defineProperty(history, 'clientHeight', { configurable: true, value: 200 })
    const input = screen.getByRole('textbox')
    fireEvent.change(input, { target: { value: 'Mensagem de teste' } })
    fireEvent.submit(input.closest('form')!)
    expect(history.scrollTop).toBe(0)
    fireEvent.click(screen.getByRole('button', { name: 'Novas mensagens ↓' }))
    expect(history.scrollTop).toBe(900)
    expect(screen.queryByRole('button', { name: 'Novas mensagens ↓' })).toBeNull()
    fireEvent.keyDown(history, { key: 'Escape' })
    expect(screen.getByRole('button', { name: 'Abrir Conversas' })).toBeTruthy()
  })
})
