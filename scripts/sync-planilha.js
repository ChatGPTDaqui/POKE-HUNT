// Prints a per-type coverage table and warns loudly (instead of silently
// shipping a hole, which is exactly the bug this whole redesign fixes) if
// any real type — or any individual roster species — ends up with zero wild
// hunt. Legendaries/base-starters are intentionally excluded from `roster`
// (see buildTypeRoster) so they don't count as "missing" here.
function reportTypeCoverage(hunts, roster) {
  const spawnedKeys = new Set();
  for (const hunt of hunts) for (const sp of Object.keys(hunt.speciesLevels)) spawnedKeys.add(sp);

  console.log('\nCobertura por tipo (elenco selvagem, exclui lendarios/iniciais-base):');
  let anyMissingType = false;
  for (const type of ALL_TYPES) {
    const primary = roster.filter((s) => s.type1 === type);
    const spawnedPrimary = primary.filter((s) => spawnedKeys.has(s.key));
    // A real type CAN have zero primary-type members in this dataset (e.g.
    // FLYING — no Gen1/2 species has Flying as its PRIMARY type, real games
    // included) and still be fully "covered" via dual-type carriers spawned
    // in its own hunt (see MIN_TYPE_POOL fallback) — count those too so this
    // report doesn't cry wolf on an expected, real-data shape.
    const spawnedAny = roster.filter((s) => (s.type1 === type || s.type2 === type) && spawnedKeys.has(s.key));
    if (spawnedAny.length === 0) anyMissingType = true;
    const note = primary.length === 0 ? ` (sem membro primario real neste dataset — via tipagem dupla)` : '';
    console.log(`  ${type.padEnd(10)} total=${primary.length} spawnado=${spawnedPrimary.length}/${primary.length} | spawnavel(incl. dual-type)=${spawnedAny.length}${note}`);
  }

  const orphans = roster.filter((s) => !spawnedKeys.has(s.key));
  if (orphans.length > 0) {
    console.log(`  AVISO: ${orphans.length} especie(s) sem nenhuma hunt: ${orphans.map((s) => s.key).join(', ')}`);
  } else {
    console.log('  OK: toda especie do elenco selvagem tem pelo menos 1 hunt.');
  }
  if (anyMissingType) console.log('  AVISO: pelo menos 1 tipo ficou sem nenhuma especie spawnavel.');
}

// Species + their real movesets/moves for the starter trio plus every
// species appearing in the chosen hunts. Moves are deduplicated globally
// (many species share moves like Tackle) — level-to-learn is per species,
// since the same move can be learned at different levels by different
// species (this is real Gen2 data, not a simplification).
// A planilha (Gen2) so tinha 'físico'/'especial', porque ate a Gen3 a
// categoria era decidida pelo TIPO do golpe. O catalogo do Ultra Sun traz a
// categoria real POR GOLPE, incluindo 'status'. Chave desconhecida cai em
// 'physical', que era o comportamento anterior para tudo que nao fosse
// 'especial'.
const CATEGORIA_DE_GOLPE = { 'físico': 'physical', 'especial': 'special', 'status': 'status' };

function syncSpeciesAndMoves(workbook, hunts) {
  console.log('Espécies + Movesets + Golpes:');
  const especiesByKey = indexByKey(workbook['Espécies'] || [], 'Chave');
  const golpesByKey = indexByKey(workbook['Golpes'] || [], 'Chave');
  const movesets = workbook['Movesets'] || [];

  const huntSpeciesKeys = new Set();
  for (const hunt of hunts) {
    for (const sp of Object.keys(hunt.speciesLevels)) huntSpeciesKeys.add(sp);
  }
  const allSpeciesKeys = new Set([...STARTER_SHEET_KEYS, ...LEGENDARY_SHEET_KEYS, ...huntSpeciesKeys]);

  // Pull in the full evolution chain of every species above too (e.g.
  // Charmander -> Charmeleon -> Charizard) so "Evoluir" can turn into a real
  // species swap instead of just a label.
  const evolutionQueue = [...allSpeciesKeys];
  while (evolutionQueue.length > 0) {
    const key = evolutionQueue.shift();
    const nextKey = especiesByKey[key] && especiesByKey[key]['Evolui Para (chave)'];
    if (nextKey && !allSpeciesKeys.has(nextKey)) {
      allSpeciesKeys.add(nextKey);
      evolutionQueue.push(nextKey);
    }
  }

  const speciesData = {};
  const abilitiesData = {};

  for (const sheetKey of allSpeciesKeys) {
    const row = especiesByKey[sheetKey];
    if (!row) {
      console.log(`  aviso: "${sheetKey}" nao encontrado na aba Espécies, pulando`);
      continue;
    }
    const ourKey = sheetKey.toLowerCase();

    const moveRows = movesets.filter((m) => m['Espécie (chave)'] === sheetKey);
    const abilities = [];
    for (const moveRow of moveRows) {
      const moveSheetKey = moveRow['Golpe (chave)'];
      const moveOurKey = moveSheetKey.toLowerCase();
      abilities.push({ key: moveOurKey, levelReq: moveRow['Nível'] });

      if (!abilitiesData[moveOurKey]) {
        const golpeRow = golpesByKey[moveSheetKey];
        if (golpeRow) {
          abilitiesData[moveOurKey] = {
            id: moveOurKey,
            name: golpeRow['Nome'],
            type: golpeRow['Tipo'],
            category: CATEGORIA_DE_GOLPE[golpeRow['Categoria (informativo)']] || 'physical',
            power: golpeRow['Poder'] != null ? golpeRow['Poder'] : 1,
            pp: golpeRow['PP'] != null ? golpeRow['PP'] : 20,
            // A planilha (Gen2) nao tem essa coluna: la, quem decidia AOE era
            // uma lista de chaves em data/abilities.ts. O catalogo do Ultra Sun
            // traz o alvo real de cada golpe.
            target: golpeRow['Alvo'] === 'aoe' ? 'aoe' : 'single',
            // Campos de EFEITO (Leva B). A planilha de Gen2 nao tinha nenhum
            // deles: golpe de status era so "fisico com 0 de poder", e efeito
            // secundario (queimar, paralisar, drenar) nao existia como dado.
            //
            // Emitidos so quando NAO sao o valor neutro — sem isso, 486 golpes
            // carregariam 8 campos zerados cada um, inflando o bundle do
            // cliente com dado que nao diz nada. Quem le trata ausente como
            // "nao tem efeito" (ver data/abilities.ts).
            ...(golpeRow['Status'] ? {
              status: golpeRow['Status'],
              statusChance: golpeRow['Chance de Status'],
            } : {}),
            ...((golpeRow['Mudancas de Stat'] || []).length ? {
              statChanges: golpeRow['Mudancas de Stat'],
              statChance: golpeRow['Chance de Stat'],
              // 'self' e a excecao (Danca das Espadas), 'target' e a regra —
              // por isso so 'self' e emitido. Quem le trata ausente como alvo.
              ...(golpeRow['Alvo do Efeito'] === 'self' ? { statTarget: 'self' } : {}),
            } : {}),
            ...(golpeRow['Chance de Flinch'] ? { flinchChance: golpeRow['Chance de Flinch'] } : {}),
            ...(golpeRow['Estagios de Critico'] ? { critStages: golpeRow['Estagios de Critico'] } : {}),
            ...(golpeRow['Dreno %'] ? { drainPercent: golpeRow['Dreno %'] } : {}),
            ...(golpeRow['Cura %'] ? { healPercent: golpeRow['Cura %'] } : {}),
            // Precisao SEMPRE sai, mesmo em 100: e o unico jeito de distinguir
            // "golpe que sempre acerta" de "campo que ninguem preencheu", e ela
            // e o que segura Horn Drill e Fissure (KO instantaneo com 30%).
            accuracy: golpeRow['Precisão'] != null ? golpeRow['Precisão'] : 100,
          };
        }
      }
    }
    abilities.sort((a, b) => a.levelReq - b.levelReq);

    const type2 = row['Tipo 2'] || null;
    const evolvesToSheetKey = row['Evolui Para (chave)'] || null;
    speciesData[ourKey] = {
      id: ourKey,
      name: row['Nome'],
      description: `Pokedex Nº${row['Nº Pokédex'] || '?'} - tipo ${row['Tipo 1']}${type2 ? '/' + type2 : ''}.`,
      type: row['Tipo 1'],
      type2,
      catchRate: row['Taxa de Captura (0-255)'],
      baseExp: row['EXP Base'],
      growthCurve: row['Curva de Crescimento'],
      base: {
        hp: row['HP'],
        atkFis: row['Ataque'],
        atkEsp: row['Ataque Especial'],
        def: row['Defesa'],
        defEsp: row['Defesa Especial'],
        speed: row['Velocidade'],
      },
      abilities,
      evolvesTo: evolvesToSheetKey ? evolvesToSheetKey.toLowerCase() : null,
      evolvesAtLevel: evolvesToSheetKey ? row['Evolui no Nível'] : null,
    };
  }

  emitData('pokes', 'SPECIES_DATA', 'SpeciesData', toJsLiteral(speciesData));
  emitData('abilities', 'ABILITIES_DATA', 'AbilitiesData', toJsLiteral(abilitiesData));
  console.log(`  ${Object.keys(speciesData).length} especies, ${Object.keys(abilitiesData).length} golpes unicos`);
  return { speciesData, abilitiesData };
}

