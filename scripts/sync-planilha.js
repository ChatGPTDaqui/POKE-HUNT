// Splits one hand-curated Kanto band (flat species list, single level range)
// into 2 biome-themed hunts — same splitByBiome used for the real Johto
// bands above, just fed a synthetic single-range speciesLevels map instead of
// per-location real data.
function splitBandByBiome(band, workbook, especiesByKey, seed) {
  const speciesLevels = {};
  for (const sp of band.species) {
    speciesLevels[sp] = { min: band.minLevel, max: band.maxLevel };
  }
  const subHunts = splitByBiome(speciesLevels, { min: band.minLevel, max: band.maxLevel }, workbook, especiesByKey, seed);
  return subHunts.map(({ biome, speciesLevels: subSpeciesLevels }) => ({
    key: `${band.key}_${biome.toLowerCase()}`,
    name: `${band.name} (${biome})`,
    avgLevel: (band.minLevel + band.maxLevel) / 2,
    minLevel: band.minLevel,
    maxLevel: band.maxLevel,
    speciesLevels: subSpeciesLevels,
    bgTheme: biome,
    unlockCost: band.unlockCost || null,
  }));
}

function buildHandAuthoredHunts(workbook, especiesByKey) {
  return KANTO_BANDS.flatMap((band, seed) => splitBandByBiome(band, workbook, especiesByKey, seed).map((hunt) => ({ ...hunt, continent: 'kanto' })));
}

// Species + their real movesets/moves for the starter trio plus every
// species appearing in the chosen hunts. Moves are deduplicated globally
// (many species share moves like Tackle) — level-to-learn is per species,
// since the same move can be learned at different levels by different
// species (this is real Gen2 data, not a simplification).
function syncSpeciesAndMoves(workbook, hunts) {
  console.log('Espécies + Movesets + Golpes:');
  const especiesByKey = indexByKey(workbook['Espécies'] || [], 'Chave');
  const golpesByKey = indexByKey(workbook['Golpes'] || [], 'Chave');
  const movesets = workbook['Movesets'] || [];

  const huntSpeciesKeys = new Set();
  for (const hunt of hunts) {
    for (const sp of Object.keys(hunt.speciesLevels)) huntSpeciesKeys.add(sp);
  }
  const allSpeciesKeys = new Set([...STARTER_SHEET_KEYS, ...huntSpeciesKeys]);

  // Pull in the full evolution chain of every species above too (e.g.
  // Charmander -> Charmeleon -> Charizard) so "Evoluir" can turn into a real
  // species swap instead of just a label.
  const evolutionQueue = [...allSpeciesKeys];
  while (evolutionQueue.length > 0) {
    const key = evolutionQueue.shift();
    const nextKey = especiesByKey[key] && especiesByKey[key]['Evolui Para (chave)'];
    if (nextKey && !allSpeciesKeys.has(nextKey)) {
      allSpeciesKeys.add(nextKey);
      evolutionQueue.push(nextKey);
    }
  }

  const speciesData = {};
  const abilitiesData = {};

  for (const sheetKey of allSpeciesKeys) {
    const row = especiesByKey[sheetKey];
    if (!row) {
      console.log(`  aviso: "${sheetKey}" nao encontrado na aba Espécies, pulando`);
      continue;
    }
    const ourKey = sheetKey.toLowerCase();

    const moveRows = movesets.filter((m) => m['Espécie (chave)'] === sheetKey);
    const abilities = [];
    for (const moveRow of moveRows) {
      const moveSheetKey = moveRow['Golpe (chave)'];
      const moveOurKey = moveSheetKey.toLowerCase();
      abilities.push({ key: moveOurKey, levelReq: moveRow['Nível'] });

      if (!abilitiesData[moveOurKey]) {
        const golpeRow = golpesByKey[moveSheetKey];
        if (golpeRow) {
          abilitiesData[moveOurKey] = {
            id: moveOurKey,
            name: golpeRow['Nome'],
            type: golpeRow['Tipo'],
            category: golpeRow['Categoria (informativo)'] === 'especial' ? 'special' : 'physical',
            power: golpeRow['Poder'] != null ? golpeRow['Poder'] : 1,
            pp: golpeRow['PP'] != null ? golpeRow['PP'] : 20,
          };
        }
      }
    }
    abilities.sort((a, b) => a.levelReq - b.levelReq);

    const type2 = row['Tipo 2'] || null;
    const evolvesToSheetKey = row['Evolui Para (chave)'] || null;
    speciesData[ourKey] = {
      id: ourKey,
      name: row['Nome'],
      description: `Pokedex Nº${row['Nº Pokédex'] || '?'} - tipo ${row['Tipo 1']}${type2 ? '/' + type2 : ''}.`,
      type: row['Tipo 1'],
      type2,
      catchRate: row['Taxa de Captura (0-255)'],
      baseExp: row['EXP Base'],
      growthCurve: row['Curva de Crescimento'],
      base: {
        hp: row['HP'],
        atkFis: row['Ataque'],
        atkEsp: row['Ataque Especial'],
        def: row['Defesa'],
        defEsp: row['Defesa Especial'],
        speed: row['Velocidade'],
      },
      abilities,
      evolvesTo: evolvesToSheetKey ? evolvesToSheetKey.toLowerCase() : null,
      evolvesAtLevel: evolvesToSheetKey ? row['Evolui no Nível'] : null,
    };
  }

  writeGenerated('pokes.generated.js', `export const SPECIES_DATA = ${toJsLiteral(speciesData)};\n`);
  writeGenerated('abilities.generated.js', `export const ABILITIES_DATA = ${toJsLiteral(abilitiesData)};\n`);
  console.log(`  ${Object.keys(speciesData).length} especies, ${Object.keys(abilitiesData).length} golpes unicos`);
  return { speciesData, abilitiesData };
}

// World layout for the 5 hunts is our own idle-game concept (bounds, spawn
// points, background) — the spreadsheet has no equivalent, so these stay
// hand-picked defaults, just parameterized by however many hunts we pick.
// Every theme shares the same real tiled background image
// (assets/Hunt background.png, user-provided — a single detailed top-down
// scene, not a small seamless texture, but tiled the same way the old
// route-only "Grass background.png" was) instead of the procedural
// checkerboard — see render/Sprites.js#drawMapBackground. `primary`/
// `secondary` stay theme-distinct as the fallback colors for whenever the
// image hasn't loaded yet (e.g. first paint).
const HUNT_BG_IMAGE = 'assets/Hunt background.png';
const BG_ROUTE = { primary: '#284b3c', secondary: '#2e5544', image: HUNT_BG_IMAGE };
const BG_CAVE = { primary: '#1c1c2b', secondary: '#242438', image: HUNT_BG_IMAGE };
const BG_TOWER = { primary: '#3e2f23', secondary: '#4a3829', image: HUNT_BG_IMAGE };

// Every biome maps to one of the 3 existing palettes by vibe — cosmetic only,
// since the real tiled image is identical across all themes (see comment
// above); this just picks the fallback color shown before it loads.
const BIOME_THEME = {
  Floresta: BG_ROUTE, Aquatico: BG_ROUTE, Eletrico: BG_ROUTE, Planicie: BG_ROUTE,
  Vulcanico: BG_CAVE, Sombrio: BG_CAVE,
  Mistico: BG_TOWER,
};

function pickBgTheme(name) {
  if (BIOME_THEME[name]) return BIOME_THEME[name];
  const lower = name.toLowerCase();
  if (lower.includes('cave')) return BG_CAVE;
  if (lower.includes('tower') || lower.includes('ruins')) return BG_TOWER;
  return BG_ROUTE;
}

const SPAWN_POINTS = [
  { x: 500, y: 320 }, { x: 900, y: 320 }, { x: 500, y: 580 },
  { x: 900, y: 580 }, { x: 700, y: 250 }, { x: 700, y: 650 },
];

const MAP_ITEM_DROPS = [
  { itemId: 'potion', chance: 0.15 },
  { itemId: 'poke_ball', chance: 0.1 },
];

function syncMapsAndEncounters(hunts, speciesData) {
  console.log('Locais_Info + Encontros (agrupados em faixas de nivel):');
  const mapsData = {};
  const encountersData = {};

  for (const hunt of hunts) {
    const mapKey = hunt.key.toLowerCase();
    const enemyPool = [];
    for (const [speciesSheetKey, levels] of Object.entries(hunt.speciesLevels)) {
      const encounterKey = `${mapKey}_${speciesSheetKey.toLowerCase()}`;
      const species = speciesData[speciesSheetKey.toLowerCase()];
      encountersData[encounterKey] = {
        id: encounterKey,
        speciesId: speciesSheetKey.toLowerCase(),
        minLevel: levels.min,
        maxLevel: levels.max,
        aggroRadius: 175,
        wanderRadius: 60,
        // Rarer species (lower real Gen2 catch rate) spawn less often within
        // the same hunt — reuses the spreadsheet's own catch-rate data as a
        // ready-made rarity signal instead of inventing new numbers (see
        // main.js#spawnEnemyAt, which picks from enemyPool by this weight).
        weight: (species && species.catchRate) || 45,
      };
      enemyPool.push(encounterKey);
    }

    mapsData[mapKey] = {
      id: mapKey,
      name: hunt.name,
      description: `Local selvagem: ${hunt.name} (nivel ${hunt.minLevel}-${hunt.maxLevel}).`,
      levelRange: [hunt.minLevel, hunt.maxLevel],
      unlockCost: hunt.unlockCost || null,
      continent: hunt.continent || 'johto',
      bounds: { width: 2800, height: 1800 },
      playerSpawn: { x: 1400, y: 900 },
      bg: pickBgTheme(hunt.bgTheme || hunt.name),
      maxEnemies: 6,
      respawnDelay: 6,
      spawnPoints: SPAWN_POINTS,
      enemyPool,
      itemDrops: MAP_ITEM_DROPS,
    };
    console.log(`  ${hunt.name} (méd. ${Math.round(hunt.avgLevel * 10) / 10}, niv ${hunt.minLevel}-${hunt.maxLevel}): ${Object.keys(hunt.speciesLevels).join(', ')}`);
  }

  writeGenerated('maps.generated.js', `export const MAPS_DATA = ${toJsLiteral(mapsData)};\n`);
  writeGenerated('enemies.generated.js', `export const ENCOUNTERS_DATA = ${toJsLiteral(encountersData)};\n`);
  return { mapsData, encountersData };
}

function main() {
  if (!fs.existsSync(XLSX_PATH)) {
    console.error(`Planilha nao encontrada em: ${XLSX_PATH}`);
    process.exit(1);
  }
  console.log(`Lendo ${path.relative(ROOT, XLSX_PATH)}...\n`);
  const workbook = readWorkbook(XLSX_PATH);

  syncFormulas(workbook);
  syncTypeChart(workbook);
  syncItemsFull(workbook);
  const especiesByKey = indexByKey(workbook['Espécies'] || [], 'Chave');
  const rawHunts = pickTopHunts(workbook, HUNT_COUNT);
  const johtoHunts = groupHuntsIntoBands(rawHunts, workbook, especiesByKey).map((hunt) => ({ ...hunt, continent: 'johto' }));
  const kantoHunts = buildHandAuthoredHunts(workbook, especiesByKey);
  const hunts = [...johtoHunts, ...kantoHunts];
  const { speciesData } = syncSpeciesAndMoves(workbook, hunts);
  syncMapsAndEncounters(hunts, speciesData);

  console.log('\nSincronizacao concluida.');
}

main();
