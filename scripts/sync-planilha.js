const SKIP_WRITE = process.env.SYNC_SKIP_WRITE === '1';

function writeGenerated(fileName, contents) {
  if (SKIP_WRITE) return;
  const filePath = path.join(DATA_DIR, fileName);
  fs.writeFileSync(filePath, GENERATED_HEADER + contents, 'utf8');
  console.log(`  -> ${path.relative(ROOT, filePath)}`);
}

// Emite o mesmo dado nos dois formatos: `.ts` tipado pro app novo e `.js`
// puro pro vanilla. `extraTs`/`extraJs` cobrem o unico caso que nao e so uma
// constante exportada (typeChart, que embute a funcao getEffectiveness).
function emitData(baseName, exportName, typeName, literal, extra) {
  if (SKIP_WRITE) return;
  // `extra.imports` cobre tipos usados so pela funcao extra (typeChart usa
  // ElementType na assinatura de getEffectiveness).
  const typeImports = [typeName, ...((extra && extra.imports) || [])].join(', ');
  const tsBody =
    `import type { ${typeImports} } from './types';\n\n` +
    `export const ${exportName}: ${typeName} = ${literal};\n` +
    (extra ? extra.ts : '');
  writeGenerated(`${baseName}.generated.ts`, tsBody);

  if (!fs.existsSync(LEGACY_DATA_DIR)) return;
  const jsBody = `export const ${exportName} = ${literal};\n` + (extra ? extra.js : '');
  const legacyPath = path.join(LEGACY_DATA_DIR, `${baseName}.generated.js`);
  fs.writeFileSync(legacyPath, GENERATED_HEADER + jsBody, 'utf8');
  console.log(`  -> ${path.relative(ROOT, legacyPath)} (fallback vanilla)`);
}

// JSON.stringify silently turns Infinity into null, and generated files are
// .js (not .json), so we can just emit real JS literals instead.
function toJsLiteral(value, indent = 0) {
  const pad = '  '.repeat(indent);
  const padInner = '  '.repeat(indent + 1);
  if (value === Infinity) return 'Infinity';
  if (value === -Infinity) return '-Infinity';
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const items = value.map((v) => padInner + toJsLiteral(v, indent + 1));
    return `[\n${items.join(',\n')}\n${pad}]`;
  }
  const keys = Object.keys(value);
  if (keys.length === 0) return '{}';
  const entries = keys.map((k) => `${padInner}${JSON.stringify(k)}: ${toJsLiteral(value[k], indent + 1)}`);
  return `{\n${entries.join(',\n')}\n${pad}}`;
}

function indexByKey(rows, keyField) {
  const map = {};
  for (const row of rows) {
    const key = row[keyField];
    if (key) map[key] = row;
  }
  return map;
}

function syncFormulas(workbook) {
  console.log('Fórmulas:');
  const rows = workbook['Fórmulas'] || [];
  const formulas = {};
  for (const row of rows) {
    const key = row['Chave'];
    if (!key) continue;
    const varsRaw = row['Variáveis disponíveis'] || '';
    const vars = varsRaw.includes('nenhuma')
      ? []
      : varsRaw.split(',').map((s) => s.trim()).filter(Boolean);
    formulas[key] = { expr: String(row['Expressão']), vars };
  }
  emitData('formulas', 'FORMULAS', 'FormulasData', toJsLiteral(formulas));
  console.log(`  ${Object.keys(formulas).length} formulas`);
  return formulas;
}

function syncTypeChart(workbook) {
  console.log('TabelaDeTipos:');
  const rows = workbook['TabelaDeTipos'] || [];
  const chart = {};
  const headerKey = 'Ataca \\ Defende';
  for (const row of rows) {
    const attackType = row[headerKey];
    if (!attackType) continue;
    const rowChart = {};
    for (const col of Object.keys(row)) {
      if (col === headerKey) continue;
      rowChart[col] = row[col];
    }
    chart[attackType] = rowChart;
  }
  // Corpo identico nos dois; so a assinatura leva tipos no .ts.
  const effectivenessBody =
    `  const row = TYPE_CHART[moveType];\n` +
    `  if (!row) return 1;\n` +
    `  const m1 = defType1 in row ? row[defType1] : 1;\n` +
    `  const m2 = defType2 && defType2 in row ? row[defType2] : 1;\n` +
    `  return m1 * m2;\n` +
    `}\n`;
  emitData('typeChart', 'TYPE_CHART', 'TypeChartData', toJsLiteral(chart), {
    imports: ['ElementType'],
    ts: `\nexport function getEffectiveness(moveType: ElementType, defType1: ElementType, defType2: ElementType | null): number {\n${effectivenessBody}`,
    js: `\nexport function getEffectiveness(moveType, defType1, defType2) {\n${effectivenessBody}`,
  });
  console.log(`  ${Object.keys(chart).length} types`);
  return chart;
}

const KIND_DESCRIPTIONS = {
  ball: 'Item de captura.',
  potion: 'Restaura HP.',
  revive: 'Reanima um POKE desmaiado.',
  status_heal: 'Cura status.',
  rod: 'Vara de pesca (mecanica ainda nao implementada).',
};

function syncItemsFull(workbook) {
  console.log('Itens (completo):');
  const rows = workbook['Itens'] || [];
  const itemsData = {};

  for (const row of rows) {
    const sheetKey = row['Chave'];
    if (!sheetKey) continue;
    const ourKey = sheetKey.toLowerCase();
    const kind = row['Tipo (kind)'];
    const item = {
      id: ourKey,
      name: row['Nome'],
      kind,
      description: KIND_DESCRIPTIONS[kind] || '',
      buyPrice: row['Preço de Compra'],
    };
    if (kind === 'ball') {
      item.captureRate = row['Multiplicador de Captura'];
    } else if (kind === 'potion') {
      const heal = row['Cura de HP'];
      item.healAmount = typeof heal === 'string' && heal.toLowerCase().includes('infinito') ? Infinity : heal;
    } else if (kind === 'revive') {
      item.reviveHpPercent = row['Cura % (revive)'];
    } else if (kind === 'status_heal') {
      // Lista, e nao um unico status: Full Heal cura seis de uma vez. Manter
      // um array ate pro Antidote evita um caso especial no consumidor.
      item.healsStatus = String(row['Cura de Status'] || '')
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean);
      if (!item.healsStatus.length) throw new Error(`item status_heal sem 'Cura de Status': ${ourKey}`);
    }
    itemsData[ourKey] = item;
  }

  emitData('items', 'ITEMS_DATA', 'ItemsData', toJsLiteral(itemsData));
  console.log(`  ${Object.keys(itemsData).length} itens`);
  return itemsData;
}

// Picks the `count` locations with the lowest average wild-encounter level
// (day period only — see Leia-me: night/morning aren't used by the game
// yet). Each returned hunt carries its overall level range plus a per-
// species level range (a species can appear at different levels in
// different hunts, e.g. Rattata is low-level almost everywhere).
function pickTopHunts(workbook, count) {
  const locations = workbook['Locais_Info'] || [];
  const dayEncounters = (workbook['Encontros'] || []).filter((r) => r['Período'] === 'day');

  const rowsByLocation = {};
  for (const row of dayEncounters) {
    const loc = row['Local (chave)'];
    if (!rowsByLocation[loc]) rowsByLocation[loc] = [];
    rowsByLocation[loc].push(row);
  }

  const candidates = [];
  for (const locRow of locations) {
    const key = locRow['Chave'];
    if (key.includes('SURF')) continue; // fishing/surfing not implemented
    const rows = rowsByLocation[key];
    if (!rows || rows.length === 0) continue;

    const levels = rows.map((r) => r['Nível']);
    const avgLevel = levels.reduce((a, b) => a + b, 0) / levels.length;
    const speciesLevels = {};
    for (const row of rows) {
      const sp = row['Espécie (chave)'];
      const lvl = row['Nível'];
      if (!speciesLevels[sp]) speciesLevels[sp] = { min: lvl, max: lvl };
      else {
        speciesLevels[sp].min = Math.min(speciesLevels[sp].min, lvl);
        speciesLevels[sp].max = Math.max(speciesLevels[sp].max, lvl);
      }
    }

    candidates.push({
      key,
      name: locRow['Nome'],
      avgLevel,
      minLevel: Math.min(...levels),
      maxLevel: Math.max(...levels),
      speciesLevels,
    });
  }

  candidates.sort((a, b) => a.avgLevel - b.avgLevel);
  return candidates.slice(0, count);
}

// The individual spreadsheet locations (pickTopHunts' raw candidates, one
// per real Johto route/floor) read as dozens of near-identical entries once
// there are 60+ of them. Bucket them into a clearer progression instead: the
// single lowest-avgLevel location stays standalone as an easy on-ramp for a
// fresh Lv1 starter, and everything else merges into ~10-level brackets
// (Lv11-20, 21-30, ...) so the hunt list reads as "what's my next bracket"
// rather than "which of these 20 same-level caves do I pick".
const BAND_SIZE = 10;

function bandRangeForLevel(avgLevel) {
  const bandIndex = Math.floor((avgLevel - 1) / BAND_SIZE);
  const from = bandIndex * BAND_SIZE + 1;
  return { bandIndex, from, to: from + BAND_SIZE - 1 };
}

